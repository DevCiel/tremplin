import AxeBuilder from '@axe-core/playwright'
import { expect, test, type Page } from '@playwright/test'
type NavigationRuntime = { NavOverflow: { getInstance(element: Element | null): { update(): void; dispose(): void } | null } }

test.use({reducedMotion:'reduce'})
const errors=new WeakMap<Page,string[]>()
test.beforeEach(({page})=>{const list:string[]=[];errors.set(page,list);page.on('pageerror',error=>list.push(error.message))})
test.afterEach(({page})=>expect(errors.get(page)).toEqual([]))
const audit=async(page:Page)=>expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa','wcag22aa']).analyze()).violations).toEqual([])

for(const topic of ['navbar','nav-overflow','toggler']) for(const theme of ['light','dark']) for(const dir of ['ltr','rtl']) {
  test(`${topic} ${theme}/${dir}: canonical markup, desktop/mobile WCAG and geometry`,async({page})=>{
    await page.addInitScript(direction=>{const set=()=>{if(!document.documentElement)return false;document.documentElement.setAttribute('dir',direction);return true};if(!set()){const observer=new MutationObserver(()=>{if(set())observer.disconnect()});observer.observe(document,{childList:true})}},dir)
    await page.goto('/components/'+topic+'/')
    await page.locator('html').evaluate((root,value)=>root.setAttribute('data-trm-theme',value),theme)
    await expect(page.locator('.docs-example').first()).toBeVisible()
    await expect(page.locator('.docs-example .stack,.docs-example .cluster,.docs-example .navbar-collapse,.docs-example .navbar-expand-md,.docs-example .dropdown-menu,.docs-example .btn-primary,.docs-example [data-trm-class-name]')).toHaveCount(0)
    expect(await page.locator('.docs-code pre').first().evaluate(root=>getComputedStyle(root).direction)).toBe('ltr')
    await audit(page)
    await page.setViewportSize({width:390,height:844})
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    await audit(page)
  })
}

test('Navbar uses container queries, native Drawer focus/Escape and a CSS mask',async({page})=>{
  await page.goto('/components/navbar/')
  const nav=page.locator('.docs-example nav').filter({has:page.locator('#container-navbar')})
  await expect(nav.locator('.navbar-toggler')).toBeHidden()
  const viewport=page.viewportSize()
  await nav.evaluate(root=>root.setAttribute('style','width:320px;max-width:100%'))
  await expect(nav.locator('.navbar-toggler')).toBeVisible()
  expect(page.viewportSize()).toEqual(viewport)
  await expect(page.locator('#container-navbar')).not.toHaveAttribute('open')
  await page.setViewportSize({width:390,height:844})
  const launcher=page.getByRole('button',{name:'Open navigation',exact:true}),panel=page.locator('#docs-navbar')
  await panel.evaluate(root=>root.addEventListener('shown.trm.drawer',()=>root.setAttribute('data-test-shown','true'),{once:true}))
  await launcher.click();await expect(panel).toHaveAttribute('data-test-shown','true')
  expect(await panel.evaluate(root=>root.matches(':modal'))).toBe(true)
  await expect(panel.locator('button[autofocus]')).toBeFocused()
  await expect(launcher).not.toHaveAttribute('aria-expanded')
  expect(await launcher.locator('.navbar-toggler-icon').evaluate(root=>getComputedStyle(root).maskImage)).not.toBe('none')
  await audit(page)
  await page.keyboard.press('Escape');await expect(panel).not.toHaveAttribute('open');await expect(launcher).toBeFocused()
})

test('NavOverflow resizes wrapper, exposes actual events and delegates Menu keyboard',async({page})=>{
  await page.goto('/components/nav-overflow/')
  const root=page.locator('#progressive-navigation')
  await root.evaluate(root=>{root.setAttribute('style','width:240px;max-width:100%');root.setAttribute('data-test-updates','0');root.setAttribute('data-test-overflows','0');root.addEventListener('update.trm.navoverflow',()=>root.setAttribute('data-test-updates',String(Number(root.getAttribute('data-test-updates'))+1)));root.addEventListener('overflow.trm.navoverflow',e=>{root.setAttribute('data-test-overflows',String(Number(root.getAttribute('data-test-overflows'))+1));root.setAttribute('data-test-count',String((e as Event & {overflowCount:number}).overflowCount))})})
  await expect(root.locator('.nav-overflow-toggle')).toBeVisible()
  await expect(root).toHaveAttribute('data-test-overflows',/[1-9]/)
  await expect(root).toHaveAttribute('data-test-updates','0')
  const more=root.getByRole('button',{name:'More',exact:true})
  await more.press('ArrowDown');await expect(more).toHaveAttribute('aria-expanded','true')
  await expect(root.locator('.nav-overflow-menu > .menu-item').first()).toBeFocused()
  await page.keyboard.press('Escape');await expect(more).toBeFocused()
  // Use the same browser bundle instance as the documentation data API.
  await page.evaluate(()=>{const {NavOverflow}=(window as unknown as {TremplinFramework:NavigationRuntime}).TremplinFramework;NavOverflow.getInstance(document.getElementById('progressive-navigation'))!.update()})
  await expect(root).toHaveAttribute('data-test-updates','1')
  await expect(page.getByRole('row').filter({hasText:'update.trm.navoverflow'})).toContainText('ResizeObserver does not dispatch update')
  await page.goto('/api/nav-overflow/');await expect(page.locator('main')).toContainText('update.trm.navoverflow')
  await expect(page.locator('main')).not.toContainText('update.trm.nav-overflow')
})

test('NavOverflow retains relocated Menu state and remaps cloned descendant identities',async({page})=>{
  await page.goto('/components/nav-overflow/')
  const root=page.locator('#submenu-navigation')
  await expect(root.locator('.nav-overflow-menu #overflow-tools')).toHaveCount(1)
  await root.locator('#overflow-note').evaluate(root=>(root as HTMLInputElement).value='Preserved draft')
  await page.evaluate(()=>{const {NavOverflow}=(window as unknown as {TremplinFramework:NavigationRuntime}).TremplinFramework;const root=document.getElementById('submenu-navigation')!;const menu=document.getElementById('overflow-tools')!;(menu as HTMLElement & {sameNode?:boolean}).sameNode=true;const instance=NavOverflow.getInstance(root)!;instance.dispose()})
  await expect(root.locator(':scope > .nav > .nav-item > #overflow-tools')).toHaveCount(1)
  await expect(root.locator('#overflow-note')).toHaveValue('Preserved draft')
  expect(await root.locator('#overflow-tools').evaluate(root=>(root as HTMLElement & {sameNode?:boolean}).sameNode)).toBe(true)
  await expect(root.locator('.nav-overflow-toggle')).toHaveCount(0)
  const cloneRoot=page.locator('#project-navigation')
  await cloneRoot.evaluate(root=>{const link=root.querySelectorAll(':scope > .nav > .nav-item > .nav-link')[1]!;const label=document.createElement('span');label.id='adaptive-clone-label';label.textContent=link.textContent;link.replaceChildren(label);link.setAttribute('aria-labelledby',label.id)})
  await page.evaluate(()=>{const {NavOverflow}=(window as unknown as {TremplinFramework:NavigationRuntime}).TremplinFramework;NavOverflow.getInstance(document.getElementById('project-navigation'))!.update()})
  const clone=cloneRoot.locator('.nav-overflow-menu .menu-item').first()
  const reference=await clone.getAttribute('aria-labelledby')
  expect(reference).toBeTruthy();expect(reference).not.toBe('adaptive-clone-label')
  expect(await clone.locator('span').getAttribute('id')).toBe(reference)
  await expect(page.locator('#adaptive-clone-label')).toHaveCount(1)
  await expect(cloneRoot.locator('.nav-overflow-keep')).toBeVisible()
})

test('Toggler targets, cancellation, multiple mutations, disabled fieldsets and no-op notifications',async({page})=>{
  await page.goto('/components/toggler/')
  const target=page.locator('#generic-panel'),trigger=page.locator('[data-trm-target="#generic-panel"]')
  await target.evaluate(root=>{root.setAttribute('data-test-toggled','0');root.addEventListener('toggled.trm.toggler',()=>root.setAttribute('data-test-toggled',String(Number(root.getAttribute('data-test-toggled'))+1)));root.addEventListener('toggle.trm.toggler',e=>e.preventDefault(),{once:true})})
  await trigger.click();await expect(target).not.toHaveClass(/bg-2/);await expect(target).toHaveAttribute('data-test-toggled','0')
  await trigger.press('Space');await expect(target).toHaveClass(/bg-2/);await expect(target).toHaveAttribute('data-test-toggled','1')
  await trigger.press('Escape');await expect(target).toHaveClass(/bg-2/);await expect(trigger).toBeFocused();await expect(trigger).not.toHaveAttribute('aria-expanded')
  await page.getByRole('button',{name:'Toggle two targets',exact:true}).click()
  await expect(page.locator('[data-tgl-pair]').first()).toHaveClass(/bg-2/);await expect(page.locator('[data-tgl-pair]').last()).toHaveClass(/border/)
  const numeric=page.getByRole('button',{name:'Toggle numeric marker',exact:true})
  await numeric.click();await expect(page.locator('#numeric-toggler')).toHaveAttribute('data-count','0');await numeric.click();await expect(page.locator('#numeric-toggler')).not.toHaveAttribute('data-count')
  const availability=page.getByRole('button',{name:'Toggle form availability',exact:true})
  await availability.click();await expect(page.locator('#toggler-name')).toBeDisabled();await availability.click();await expect(page.locator('#toggler-name')).toBeEnabled()
  await expect(page.getByRole('button',{name:'Unavailable toggle',exact:true})).toBeDisabled()
  for(const [id,label] of [['protected-toggler','Try protected id'],['null-toggler','Try null value']]) {
    await page.locator('#'+id).evaluate(root=>root.addEventListener('toggled.trm.toggler',()=>root.setAttribute('data-test-notified','true'),{once:true}))
    await page.getByRole('button',{name:label,exact:true}).click();await expect(page.locator('#'+id)).toHaveAttribute('data-test-notified','true')
  }
  await expect(page.locator('#replacement')).toHaveCount(0)
  await expect(page.locator('#null-toggler')).not.toHaveClass(/null/)
  await expect(page.getByRole('region',{name:'Scrollable Toggler options'}).getByRole('row')).toHaveCount(3)
  await expect(page.locator('main')).not.toContainText('This component has no configuration options.')
  await page.goto('/api/toggler/')
  await expect(page.getByRole('region',{name:'Scrollable Toggler options'}).getByRole('row')).toHaveCount(3)
  await expect(page.locator('main')).toContainText('data-trm-attribute')
})
