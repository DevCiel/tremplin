import AxeBuilder from '@axe-core/playwright'
import { expect, test, type Page } from '@playwright/test'

test.use({reducedMotion:'reduce'})
const errors=new WeakMap<Page,string[]>()
test.beforeEach(({page})=>{const list:string[]=[];errors.set(page,list);page.on('pageerror',e=>list.push(e.message))})
test.afterEach(({page})=>{expect(errors.get(page)).toEqual([])})
const audit=async(page:Page)=>expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa','wcag22aa']).analyze()).violations).toEqual([])
for(const topic of ['chip','table'])for(const theme of ['light','dark'])for(const dir of ['ltr','rtl']) {
  test(`${topic} ${theme}/${dir}: canonical markup, desktop/mobile WCAG and geometry`,async({page})=>{
    await page.goto('/components/'+topic+'/')
    await page.locator('html').evaluate((root,s)=>{root.setAttribute('dir',s.dir);root.setAttribute('data-trm-theme',s.theme)},{dir,theme})
    await expect(page.locator('.docs-example').first()).toBeVisible()
    await expect(page.locator('.docs-example .chip-remove,.docs-example .chip-sm,.docs-example .chip-avatar,.docs-example .table-success,.docs-example .table-responsive-md')).toHaveCount(0)
    expect(await page.locator('.docs-code pre').first().evaluate(root=>getComputedStyle(root).direction)).toBe('ltr')
    await audit(page)
    await page.setViewportSize({width:390,height:844});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);await audit(page)
  })
}
test('standalone Chip application filter, removal focus/status, disabled controls and actual sizing',async({page})=>{
  await page.goto('/components/chip/')
  const button=page.getByRole('button',{name:'Design filter',exact:true})
  await button.focus();await expect(button).toBeFocused();await expect(button).toHaveCSS('outline-style','solid')
  await page.keyboard.press('Space');await expect(button).toHaveAttribute('aria-pressed','true');await expect(button).toHaveClass(/active/)
  await page.keyboard.press('Enter');await expect(button).toHaveAttribute('aria-pressed','false');await expect(button).not.toHaveClass(/active/)
  const disabled=page.getByRole('button',{name:'Unavailable filter',exact:true});await expect(disabled).toBeDisabled();await disabled.evaluate(el=>(el as HTMLButtonElement).click());await expect(disabled).toHaveAttribute('aria-pressed','false')
  const remove=page.getByRole('button',{name:'Remove Design filter',exact:true});await remove.focus();await page.keyboard.press('Enter')
  await expect(page.locator('#removable-design-chip')).toHaveCount(0);await expect(page.locator('#chip-removal-status')).toHaveText('Design filter removed.');await expect(page.locator('#chip-removal-next')).toBeFocused()
  const sizes=await page.locator('.docs-example .chip[style]').evaluateAll(els=>els.map(el=>el.getBoundingClientRect().height));expect(sizes).toEqual([36])
  await expect(page.locator('.docs-example .chip').first()).toHaveCSS('height','28px')
  await expect(page.getByRole('link',{name:'Tremplin source'})).toHaveAttribute('href','https://github.com/DevCiel/tremplin/blob/main/src/scss/_chip.scss')
})
test('Table container-only stacking, native horizontal keyboard scrolling and breakpoint overflow',async({page})=>{
  await page.goto('/components/table/')
  const wrapper=page.locator('#table-stack-demo'),table=wrapper.getByRole('table'),cell=table.locator('tbody td').nth(1)
  const viewport=page.viewportSize()!
  await wrapper.evaluate(el=>(el as HTMLElement).style.inlineSize='820px');await expect(cell).toHaveCSS('display','table-cell')
  await wrapper.evaluate(el=>(el as HTMLElement).style.inlineSize='360px');await expect(cell).toHaveCSS('display','block')
  expect(page.viewportSize()).toEqual(viewport)
  expect(await cell.evaluate(el=>getComputedStyle(el,'::before').content)).toBe('"Role"')
  await expect(table.locator('thead')).toHaveCSS('position','absolute');await expect(table.getByRole('columnheader')).toHaveCount(3)
  const overflow=page.locator('#table-scroll-demo');await overflow.evaluate(el=>(el as HTMLElement).style.inlineSize='320px');await overflow.focus();await expect(overflow).toBeFocused()
  expect(await overflow.evaluate(el=>el.scrollWidth>el.clientWidth)).toBe(true)
  await page.keyboard.press('ArrowRight');await expect.poll(()=>overflow.evaluate(el=>el.scrollLeft)).toBeGreaterThan(0)
  const md=page.getByRole('region',{name:'md responsive invoice region',exact:true});await expect(md).toHaveCSS('overflow-x','visible')
  await page.setViewportSize({width:600,height:844});await expect(md).toHaveCSS('overflow-x','auto')
  await audit(page)
})
test('Table accent, nesting, compact padding, card clipping and semantic footer stay CSS-only',async({page})=>{
  await page.goto('/components/table/')
  const defaultCell=page.locator('.docs-example').first().locator('tbody td').first()
  await expect(defaultCell).toHaveCSS('padding-left','8px')
  const compact=page.getByRole('table',{name:'Compact invoices',exact:true}).locator('tbody td').first();await expect(compact).toHaveCSS('padding-left','4px')
  const outer=page.locator('#outer-invoice-table'),inner=outer.getByRole('table',{name:'Nested batch invoices',exact:true})
  const accent=async(selector:string)=>page.locator(selector).evaluate(el=>getComputedStyle(el).getPropertyValue('--trm-table-bg-type').trim())
  expect(await accent('#outer-invoice-table > tbody > tr > td')).not.toBe('')
  expect(await inner.locator('tbody td').first().evaluate(el=>getComputedStyle(el).getPropertyValue('--trm-table-bg-type').trim())).toBe('')
  const card=page.getByRole('table',{name:'Invoice card',exact:true});await expect(card).toHaveCSS('margin-bottom','0px');await expect(card.locator('tbody tr').last().locator('td').last()).toHaveCSS('border-bottom-width','0px')
  await expect(card.locator('..')).toHaveCSS('overflow-x','hidden')
  await expect(page.getByRole('table',{name:'Invoice totals',exact:true}).locator('tfoot th')).toHaveText('Total billed')
  await expect(page.locator('.docs-example [role="grid"],.docs-example [aria-sort],.docs-example [aria-selected]')).toHaveCount(0)
  await expect(page.getByRole('link',{name:'Tremplin source'})).toHaveAttribute('href','https://github.com/DevCiel/tremplin/blob/main/src/scss/content/_tables.scss')
})
