import AxeBuilder from '@axe-core/playwright'
import { expect, test, type Page } from '@playwright/test'

test.use({ reducedMotion: 'reduce' })
const errors = new WeakMap<Page, string[]>()
test.beforeEach(({ page }) => { const list: string[] = []; errors.set(page, list); page.on('pageerror', error => list.push(error.message)) })
test.afterEach(({ page }) => { expect(errors.get(page)).toEqual([]) })
const audit = async (page: Page) => expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa']).analyze()).violations).toEqual([])

for (const name of ['button', 'alert', 'badge', 'card']) for (const theme of ['light', 'dark']) for (const dir of ['ltr', 'rtl']) {
  test(`${name} ${theme}/${dir}: actual styling, readable controls and mobile layout`, async ({ page }) => {
    await page.goto('/components/' + name + '/')
    await page.locator('html').evaluate((root, state) => { root.setAttribute('data-trm-theme', state.theme); root.setAttribute('dir', state.dir) }, { theme, dir })
    const first = page.locator('.docs-example').first()
    await expect(first).toBeVisible()
    await expect(first.locator('.cluster, .stack, .btn-primary, .btn-outline-primary, .alert-dismissible')).toHaveCount(0)
    expect(await first.evaluate(root => getComputedStyle(root).direction)).toBe(dir)
    expect(await page.locator('.docs-code pre').first().evaluate(root => getComputedStyle(root).direction)).toBe('ltr')
    if (name === 'button') {
      expect(await first.locator('.hstack').evaluate(root => getComputedStyle(root).display)).toBe('flex')
      const size = await page.getByRole('button', { name: 'Add item', exact: true }).evaluate(root => ({ width: root.getBoundingClientRect().width, height: root.getBoundingClientRect().height }))
      expect(size.width).toBeGreaterThan(0)
      expect(size.width).toBeLessThan(64)
      expect(size.height).toBeLessThan(64)
    } else if (name === 'alert') {
      const close = first.getByRole('button', { name: 'Dismiss', exact: true })
      expect(await close.evaluate(root => getComputedStyle(root).maskImage)).not.toBe('none')
      await expect(close).toHaveText('')
    } else if (name === 'badge') {
      expect(await first.locator('.badge').evaluate(root => getComputedStyle(root).display)).toBe('inline-flex')
      await expect(page.getByRole('button', { name: 'Notifications 4 unread', exact: true })).toBeVisible()
    } else {
      expect(await first.locator('.card-body').evaluate(root => getComputedStyle(root).display)).toBe('flex')
      expect(await first.locator('.card-body').evaluate(root => parseFloat(getComputedStyle(root).rowGap))).toBeGreaterThan(0)
      const action = first.getByRole('link', { name: 'Open project', exact: true })
      await expect(action).toHaveAttribute('href', '/getting-started/install/')
    }
    await audit(page)
    await page.setViewportSize({ width: 390, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await audit(page)
  })
}

test('Button pressed state, native checkbox semantics and disabled actions remain distinct', async ({ page }) => {
  await page.goto('/components/button/')
  await expect(page.locator('pre code').filter({ hasText: 'document.querySelector' }).first()).toContainText('[data-trm-toggle="button"]')
  const introductionToggle = page.getByRole('button', { name: 'Toggle example action', exact: true })
  await introductionToggle.click()
  await expect(introductionToggle).toHaveAttribute('aria-pressed', 'true')
  await introductionToggle.press('Space')
  await expect(introductionToggle).toHaveAttribute('aria-pressed', 'false')
  const toggle = page.getByRole('button', { name: 'Toggle notifications', exact: true })
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await expect(toggle).toHaveClass(/active/)
  await toggle.press('Space')
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await expect(toggle).not.toHaveClass(/active/)
  await page.getByText('Email updates', { exact: true }).click()
  const checkbox = page.getByRole('checkbox', { name: 'Email updates', exact: true })
  await expect(checkbox).toBeChecked()
  await checkbox.focus()
  await checkbox.press('Space')
  await expect(checkbox).not.toBeChecked()
  await expect(page.getByRole('checkbox', { name: 'Required updates', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Disabled', exact: true })).toBeDisabled()
  await expect(page.getByRole('link', { name: 'Unavailable link', exact: true })).not.toHaveAttribute('href')
})

test('Alert dismissal is cancelable, removes the element and preserves the instant option', async ({ page }) => {
  await page.goto('/components/alert/')
  await expect(page.locator('.docs-variant').filter({ has: page.getByRole('heading', { name: 'Dismissible alert', exact: true }) })).toContainText('removes the element after its exit transition, then emits closed')
  await expect(page.locator('#data-attributes + p')).toContainText('data-trm-dismiss="alert"')
  await expect(page.getByRole('row').filter({ hasText: 'closed.trm.alert' })).toContainText('After removal')
  const notice = page.locator('#export-notice')
  await notice.evaluate(root => root.addEventListener('close.trm.alert', event => { event.preventDefault(); root.setAttribute('data-canceled', 'true') }, { once: true }))
  await notice.getByRole('button', { name: 'Dismiss export notification', exact: true }).click()
  await expect(notice).toHaveAttribute('data-canceled', 'true')
  await expect(notice).toBeVisible()
  await Promise.all([
    notice.evaluate(root => new Promise<void>(resolve => root.addEventListener('closed.trm.alert', () => resolve(), { once: true }))),
    notice.getByRole('button', { name: 'Dismiss export notification', exact: true }).click()
  ])
  await expect(notice).toHaveCount(0)
  await page.locator('#instant-notice').getByRole('button', { name: 'Dismiss temporary notice', exact: true }).click()
  await expect(page.locator('#instant-notice')).toHaveCount(0)
  await page.goto('/api/alert/')
  await expect(page.locator('main p').filter({ hasText: 'data-trm-dismiss="alert"' })).toContainText('named native close button')
  await expect(page.getByText('This component is initialized through JavaScript.', { exact: true })).toHaveCount(0)
})

test('Card groups follow their container and decorative image sizing preserves its ratio', async ({ page }) => {
  await page.goto('/components/card/')
  const section = page.locator('.docs-variant').filter({ has: page.getByRole('heading', { name: 'Card groups', exact: true }) })
  const container = section.locator('.contains-inline'), group = section.locator('.card-group')
  await container.evaluate(root => { (root as HTMLElement).style.inlineSize = '280px' })
  expect(await group.evaluate(root => getComputedStyle(root).display)).toBe('block')
  await container.evaluate(root => { (root as HTMLElement).style.inlineSize = '680px' })
  expect(await group.evaluate(root => getComputedStyle(root).display)).toBe('flex')
  const bottoms = await group.locator('.card-footer').evaluateAll(roots => roots.map(root => root.getBoundingClientRect().bottom))
  expect(Math.max(...bottoms) - Math.min(...bottoms)).toBeLessThan(2)
  await container.evaluate(root => { (root as HTMLElement).style.removeProperty('inline-size') })
  const image = page.locator('.docs-example img').first()
  await image.evaluate(root => (root as HTMLImageElement).decode())
  const size = await image.boundingBox()
  expect(size!.height / size!.width).toBeCloseTo(.5, 2)
})

