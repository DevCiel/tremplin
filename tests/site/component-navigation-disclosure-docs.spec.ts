import AxeBuilder from '@axe-core/playwright'
import { expect, test, type Page } from '@playwright/test'

test.use({ reducedMotion: 'reduce' })
const errors = new WeakMap<Page, string[]>()
test.beforeEach(({ page }) => { const list: string[] = []; errors.set(page, list); page.on('pageerror', error => list.push(error.message)) })
test.afterEach(({ page }) => { expect(errors.get(page)).toEqual([]) })
const audit = async (page: Page) => expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa']).analyze()).violations).toEqual([])

for (const topic of ['button-group', 'close-button', 'nav', 'accordion']) for (const theme of ['light', 'dark']) for (const dir of ['ltr', 'rtl']) {
  test(`${topic} ${theme}/${dir}: canonical presentation, desktop/mobile and accessibility`, async ({ page }) => {
    await page.goto('/components/' + topic + '/')
    await page.locator('html').evaluate((root, state) => { root.setAttribute('data-trm-theme', state.theme); root.setAttribute('dir', state.dir) }, { theme, dir })
    const examples = page.locator('.docs-example')
    await expect(examples.first()).toBeVisible()
    await expect(page.locator('#javascript + p')).toContainText(topic === 'accordion' ? 'no Accordion JavaScript plugin' : topic === 'close-button' ? 'Alert JavaScript' : 'Menu JavaScript')
    await expect(examples.locator('.cluster, .stack, .btn-primary, .btn-outline-primary, .accordion-button, .accordion-collapse')).toHaveCount(0)
    expect(await examples.first().evaluate(root => getComputedStyle(root).direction)).toBe(dir)
    expect(await page.locator('.docs-code pre').first().evaluate(root => getComputedStyle(root).direction)).toBe('ltr')
    if (topic === 'accordion') {
      const header = examples.first().locator('summary').first()
      expect(await header.evaluate(root => getComputedStyle(root).display)).toBe('flex')
      const icon = header.locator('svg')
      await expect(icon).toHaveAttribute('aria-hidden', 'true')
      const size = await icon.boundingBox()
      expect(size!.width).toBeGreaterThanOrEqual(15)
      expect(size!.width).toBeLessThanOrEqual(20)
      await expect(header).not.toHaveAttribute('data-trm-toggle')
    } else if (topic === 'button-group') {
      expect(await examples.first().getByRole('group').evaluate(root => getComputedStyle(root).display)).toBe('inline-flex')
    } else if (topic === 'nav') {
      expect(await examples.first().getByRole('navigation').evaluate(root => getComputedStyle(root).display)).toBe('flex')
      await expect(examples.locator('[role="tab"], [role="tablist"]')).toHaveCount(0)
    } else {
      const close = examples.first().getByRole('button', { name: 'Close example', exact: true })
      expect(await close.evaluate(root => getComputedStyle(root).maskImage)).not.toBe('none')
      await expect(close).toHaveText('')
      const table = page.getByRole('region', { name: 'Scrollable CSS variables', exact: true }).locator('table')
      expect(await table.evaluate(root => getComputedStyle(root).tableLayout)).toBe('fixed')
      const columns = await table.locator('th').evaluateAll(cells => cells.map(cell => cell.getBoundingClientRect().width))
      expect(columns[2]! / columns.reduce((sum, width) => sum + width, 0)).toBeGreaterThan(.3)
    }
    await audit(page)
    await page.setViewportSize({ width: 390, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await audit(page)
  })
}

test('Button groups size direct controls and preserve native checkbox/radio selection', async ({ page }) => {
  await page.goto('/components/button-group/')
  const sizes = page.locator('.docs-variant').filter({ has: page.getByRole('heading', { name: 'Group sizes', exact: true }) })
  const heights = await sizes.locator('.btn-group > button:first-child').evaluateAll(buttons => buttons.map(button => button.getBoundingClientRect().height))
  expect(heights).toHaveLength(4)
  expect(heights[0]).toBeLessThan(heights[1]!)
  expect(heights[1]).toBeLessThan(heights[2]!)
  expect(heights[2]).toBeLessThan(heights[3]!)
  await page.getByText('Bold', { exact: true }).click()
  const bold = page.getByRole('checkbox', { name: 'Bold', exact: true })
  await expect(bold).toBeChecked()
  await bold.focus()
  await bold.press('Space')
  await expect(bold).not.toBeChecked()
  await expect(page.getByRole('checkbox', { name: 'Locked', exact: true })).toBeDisabled()
  await page.getByText('Align center', { exact: true }).click()
  await expect(page.getByRole('radio', { name: 'Align center', exact: true })).toBeChecked()
  await expect(page.getByRole('radio', { name: 'Align start', exact: true })).not.toBeChecked()
  await expect(page.getByRole('radio', { name: 'Align end', exact: true })).not.toBeChecked()
  await expect(page.getByRole('textbox', { name: 'Page number', exact: true })).toHaveValue('1')
})

test('Close masks load, native disabled is retained, and Alert dismissal stays cancelable', async ({ page }) => {
  await page.goto('/components/close-button/')
  const close = page.getByRole('button', { name: 'Close example', exact: true })
  const mask = await close.evaluate(async root => {
    const style = getComputedStyle(root), source = /^url\(["']?(.*?)["']?\)$/.exec(style.maskImage)?.[1]
    if (!source) throw new Error('Missing mask')
    const image = new Image(); image.src = source; await image.decode()
    return { loaded: image.naturalWidth > 0, width: root.getBoundingClientRect().width, background: style.backgroundColor }
  })
  expect(mask.loaded).toBe(true)
  expect(mask.width).toBeGreaterThanOrEqual(20)
  expect(mask.background).not.toBe('rgba(0, 0, 0, 0)')
  await close.click()
  await expect(close).toBeVisible() // A mask alone invents no close-page action.
  await expect(page.getByRole('button', { name: 'Unavailable close action', exact: true })).toBeDisabled()
  const alert = page.locator('#reference-close-alert')
  await alert.evaluate(root => root.addEventListener('close.trm.alert', event => event.preventDefault(), { once: true }))
  await alert.getByRole('button', { name: 'Dismiss example message' }).click()
  await expect(alert).toBeVisible()
  await alert.getByRole('button', { name: 'Dismiss example message' }).click()
  await expect(alert).toHaveCount(0)
})

test('Nested group and Nav menus retain real opening, focus, Escape and narrow-screen positioning', async ({ page }) => {
  for (const [topic, triggerName] of [['button-group', 'More actions'], ['nav', 'More sections']] as const) {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto('/components/' + topic + '/')
    const trigger = page.getByRole('button', { name: triggerName, exact: true })
    await trigger.focus()
    await trigger.press('ArrowDown')
    const menu = page.getByRole('menu', { name: triggerName, exact: true })
    await expect(menu).toBeVisible()
    await expect(trigger).toHaveAttribute('aria-expanded', 'true')
    await expect(menu.getByRole('menuitem').first()).toBeFocused()
    const rect = await menu.boundingBox()
    expect(rect!.x).toBeGreaterThanOrEqual(0)
    expect(rect!.x + rect!.width).toBeLessThanOrEqual(390)
    await audit(page)
    await page.keyboard.press('Escape')
    await expect(menu).toBeHidden()
    await expect(trigger).toBeFocused()
    await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  }
})

test('Native Accordion supplies exclusive/independent/nested state and toggle events without Collapse', async ({ page }) => {
  await page.goto('/components/accordion/')
  const first = page.locator('#project-overview'), second = page.locator('#project-access')
  await expect(first).toHaveAttribute('open', '')
  await second.locator('summary').focus()
  await second.locator('summary').press('Enter')
  await expect(second).toHaveAttribute('open', '')
  await expect(first).not.toHaveAttribute('open')
  await second.locator('summary').press('Space')
  await expect(second).not.toHaveAttribute('open')
  await second.evaluate(root => { root.addEventListener('toggle', () => root.setAttribute('data-native-toggle', 'received'), { once: true }); (root as HTMLDetailsElement).open = true })
  await expect(second).toHaveAttribute('data-native-toggle', 'received')
  const independent = page.locator('.docs-variant').filter({ has: page.getByRole('heading', { name: 'Independent panels', exact: true }) })
  await independent.locator('details').nth(1).locator('summary').click()
  await expect(independent.locator('details[open]')).toHaveCount(2)
  const nested = page.locator('.docs-variant').filter({ has: page.getByRole('heading', { name: 'Nested native groups', exact: true }) })
  const children = nested.locator('details[name="nested-inner-guide"]')
  await children.nth(1).locator('summary').click()
  await expect(children.nth(1)).toHaveAttribute('open', '')
  await expect(children.first()).not.toHaveAttribute('open')
  await expect(nested.locator('details[name="nested-outer-guide"]').first()).toHaveAttribute('open', '')
  await expect(page.locator('.docs-example [data-trm-toggle="collapse"], .docs-example .accordion-button')).toHaveCount(0)
  await audit(page)
})
