test('Tooltip first focus, cancellation, sanitized HTML and top-layer Escape ordering', async ({ page }) => {
  await page.goto('/components/tooltip/')
  const trigger=page.locator('#example-tooltip')
  await trigger.evaluate(root=>root.addEventListener('show.trm.tooltip',e=>{e.preventDefault();root.setAttribute('data-test-canceled','show')},{once:true}))
  await trigger.focus(); await expect(trigger).toHaveAttribute('data-test-canceled','show'); await expect(trigger).not.toHaveAttribute('aria-describedby')
  await trigger.evaluate(root=>(root as HTMLElement).blur()); await trigger.focus()
  await expect(trigger).toHaveAttribute('aria-describedby',/.+/)
  let id=await trigger.getAttribute('aria-describedby'); await expect(page.locator('#'+id)).toBeVisible()
  await page.keyboard.press('Escape'); await expect(page.locator('#'+id)).toHaveCount(0); await expect(trigger).toBeFocused()
  const formatted=page.getByRole('button',{name:'Formatted help',exact:true}); await formatted.focus(); await expect(formatted).toHaveAttribute('aria-describedby',/.+/)
  id=await formatted.getAttribute('aria-describedby'); await expect(page.locator('#'+id+' strong')).toHaveText('Review'); await page.keyboard.press('Escape')
  await page.goto('/components/dialog/'); await open(page,'dialog','dialog-overlays','Open overlay review')
  const child=page.locator('#dialog-tooltip'); await child.focus(); await expect(child).toHaveAttribute('aria-describedby',/.+/)
  id=await child.getAttribute('aria-describedby'); await expect(page.locator('#dialog-overlays #'+id)).toBeVisible()
  await page.keyboard.press('Escape'); await expect(page.locator('#'+id)).toHaveCount(0); await expect(page.locator('#dialog-overlays')).toHaveAttribute('open','')
  await watch(page,'dialog-overlays','hidden.trm.dialog'); await page.keyboard.press('Escape'); await expect(page.locator('#dialog-overlays')).toHaveAttribute('data-test-complete','hidden.trm.dialog')
})

test('Popover click versus focus dismissal, sanitized output, geometry and generated cleanup', async ({ page }) => {
  await page.setViewportSize({width:390,height:844}); await page.goto('/components/popover/')
  const trigger=page.locator('#example-popover')
  await trigger.click(); await expect(trigger).toHaveAttribute('aria-describedby',/.+/)
  let id=await trigger.getAttribute('aria-describedby'), output=page.locator('#'+id)
  await expect(output).toBeVisible(); await expect(output).toHaveAttribute('role','tooltip'); await expect(trigger).not.toHaveAttribute('aria-expanded')
  const box=(await output.boundingBox())!; expect(box.x).toBeGreaterThanOrEqual(0); expect(box.x+box.width).toBeLessThanOrEqual(390)
  await page.locator('h1').click(); await expect(output).toBeVisible()
  await page.keyboard.press('Escape'); await expect(output).toHaveCount(0)
  const focus=page.locator('#focus-popover'); await focus.focus(); await expect(focus).toHaveAttribute('aria-describedby',/.+/)
  id=await focus.getAttribute('aria-describedby'); output=page.locator('#'+id)
  await output.locator('.popover-body').click(); await expect(output).toBeVisible()
  await page.locator('h1').click(); await expect(output).toHaveCount(0)
  const html=page.getByRole('button',{name:'Show release',exact:true}); await html.click(); await expect(html).toHaveAttribute('aria-describedby',/.+/)
  id=await html.getAttribute('aria-describedby'); await expect(page.locator('#'+id+' strong')).toHaveText('v0.8')
  await audit(page); await page.keyboard.press('Escape'); await expect(page.locator('#'+id)).toHaveCount(0)
})
