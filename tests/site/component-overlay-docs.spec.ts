import AxeBuilder from '@axe-core/playwright'
import { expect, test, type Page } from '@playwright/test'

test.use({ reducedMotion: 'reduce' })
const errors = new WeakMap<Page, string[]>()
test.beforeEach(({ page }) => { const list: string[] = []; errors.set(page, list); page.on('pageerror', e => list.push(e.message)) })
test.afterEach(({ page }) => { expect(errors.get(page)).toEqual([]) })
const audit = async (page: Page) => expect((await new AxeBuilder({ page }).withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa','wcag22aa']).analyze()).violations).toEqual([])
const watch = async (page: Page, id: string, type: string) => page.locator('#'+id).evaluate((root, event) => { root.removeAttribute('data-test-complete'); root.addEventListener(event, () => root.setAttribute('data-test-complete', event), { once: true }) }, type)
const open = async (page: Page, kind: 'dialog'|'drawer', id: string, label: string) => { await watch(page,id,'shown.trm.'+kind); await page.getByRole('button',{name:label,exact:true}).click(); await expect(page.locator('#'+id)).toHaveAttribute('data-test-complete','shown.trm.'+kind) }
const dismiss = async (page: Page, kind: 'dialog'|'drawer', id: string, label: string) => { await watch(page,id,'hidden.trm.'+kind); await page.locator('#'+id).getByRole('button',{name:label,exact:true}).click(); await expect(page.locator('#'+id)).toHaveAttribute('data-test-complete','hidden.trm.'+kind) }

for (const topic of ['dialog','drawer','tooltip','popover']) for (const theme of ['light','dark']) for (const dir of ['ltr','rtl']) {
  test(`${topic} ${theme}/${dir}: canonical markup, initial document direction, desktop/mobile accessibility`, async ({ page }) => {
    await page.addInitScript(direction => {
      const set = () => { if (!document.documentElement) return false; document.documentElement.dir = direction; return true }
      if (!set()) { const observer = new MutationObserver(() => { if (set()) observer.disconnect() }); observer.observe(document, { childList: true }) }
    }, dir)
    await page.goto('/components/'+topic+'/')
    await page.locator('html').evaluate((root,t) => root.setAttribute('data-trm-theme',t),theme)
    await expect(page.locator('html')).toHaveAttribute('dir',dir)
    await expect(page.locator('.docs-example').first()).toBeVisible()
    await expect(page.locator('.docs-example .cluster, .docs-example .stack, .docs-example .btn-primary, .docs-example .drawer-sm, .docs-example .drawer-lg, .docs-example .bottom-sheet, .docs-example section.drawer, .docs-example [data-trm-placement="start"], .docs-example [data-trm-placement="end"]')).toHaveCount(0)
    expect(await page.locator('.docs-code pre').first().evaluate(root=>getComputedStyle(root).direction)).toBe('ltr')
    await audit(page)
    await page.setViewportSize({width:390,height:844})
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    await audit(page)
  })
}

test('Dialog cancellation, native modal/nonmodal policy, focus return, static rejection and swap', async ({ page }) => {
  await page.goto('/components/dialog/')
  const panel=page.locator('#confirm'), trigger=page.getByRole('button',{name:'Open dialog',exact:true})
  await panel.evaluate(root=>root.addEventListener('show.trm.dialog',e=>{e.preventDefault();root.setAttribute('data-test-canceled','show')},{once:true}))
  await trigger.click(); await expect(panel).toHaveAttribute('data-test-canceled','show'); await expect(panel).not.toHaveAttribute('open','')
  await open(page,'dialog','confirm','Open dialog')
  expect(await panel.evaluate(root=>root.matches(':modal'))).toBe(true)
  await expect(page.locator('html')).toHaveClass(/dialog-open/)
  await expect(panel.getByRole('button',{name:'Close Publish project?',exact:true})).toBeFocused()
  await trigger.evaluate(root=>(root as HTMLElement).focus())
  expect(await panel.evaluate(root=>root.contains(document.activeElement))).toBe(true)
  await audit(page)
  await panel.evaluate(root=>root.addEventListener('hide.trm.dialog',e=>e.preventDefault(),{once:true}))
  await panel.getByRole('button',{name:'Confirm',exact:true}).click(); await expect(panel).toHaveAttribute('open','')
  await dismiss(page,'dialog','confirm','Confirm'); await expect(panel).not.toHaveAttribute('open',''); await expect(trigger).toBeFocused()
  await open(page,'dialog','dialog-nonmodal','Open inspector')
  expect(await page.locator('#dialog-nonmodal').evaluate(root=>root.matches(':modal'))).toBe(false)
  await expect(page.locator('html')).not.toHaveClass(/dialog-open/)
  await dismiss(page,'dialog','dialog-nonmodal','Done inspecting')
  await open(page,'dialog','dialog-static','Review unsaved changes')
  await watch(page,'dialog-static','hidePrevented.trm.dialog'); await page.keyboard.press('Escape'); await expect(page.locator('#dialog-static')).toHaveAttribute('data-test-complete','hidePrevented.trm.dialog'); await expect(page.locator('#dialog-static')).toHaveAttribute('open','')
  await dismiss(page,'dialog','dialog-static','Keep editing')
  await open(page,'dialog','dialog-first','Start review flow'); await open(page,'dialog','dialog-second','Continue to second review')
  await expect(page.locator('#dialog-first')).not.toHaveAttribute('open','')
  await dismiss(page,'dialog','dialog-second','Close Second review')
  await expect(page.getByRole('row').filter({hasText:'cancel.trm.dialog'})).toContainText('not the cancelable hide gate')
})

