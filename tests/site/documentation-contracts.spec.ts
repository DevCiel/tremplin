import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'

for (const [route, id] of [['forms/combobox', 'forms-combo-city'], ['components/combobox', 'guide-city']] as const) {
  test(route + ': search moves real option focus and submits a single value', async ({ page }) => {
    await page.goto('/' + route + '/')
    const trigger = page.locator('#' + id)
    await trigger.click()
    const menu = page.locator('#' + id + '-menu')
    const search = menu.getByRole('searchbox', { name: 'Search City', exact: true })
    await expect(search).toBeFocused()
    await search.fill('absent')
    await expect(menu.locator('.combobox-no-results')).toBeVisible()
    await search.fill('lon')
    await search.press('ArrowDown')
    await expect(menu.getByRole('option', { name: 'London', exact: true })).toBeFocused()
    const results = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()
    expect(results.violations).toEqual([])
    await page.keyboard.press('Enter')
    await expect(trigger.locator('.combobox-value')).toHaveText('London')
    await expect(page.locator('input[name="' + id + '"]')).toHaveValue('lon')
    await expect(trigger).toBeFocused()
    await expect(trigger).not.toHaveAttribute('aria-activedescendant')
    await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  })
}

test('multiple choices stay open, disabled choices are skipped and names remain accessible', async ({ page }) => {
  await page.goto('/components/combobox/')
  const trigger = page.locator('#guide-offices'), menu = page.locator('#guide-offices-menu')
  await trigger.click()
  await menu.getByRole('option', { name: 'Paris', exact: true }).click()
  await menu.getByRole('option', { name: 'London', exact: true }).click()
  await expect(trigger.locator('.combobox-value')).toHaveText('2 selected')
  await expect(page.locator('input[name="guide-offices"]')).toHaveValue('par,lon')
  await expect(menu).toHaveClass(/show/)
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()).violations).toEqual([])
  await page.keyboard.press('Escape')
  await page.locator('#guide-plan').click()
  const planMenu = page.locator('#guide-plan-menu')
  await planMenu.getByRole('searchbox').press('ArrowDown')
  await expect(planMenu.getByRole('option', { name: 'Starter', exact: true })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(planMenu.getByRole('option', { name: 'Starter', exact: true })).toBeFocused()
  await expect(planMenu.getByRole('option', { name: /Enterprise/ })).toBeDisabled()
})

test('navbar Drawer resizes inline without inventing Toggler disclosure policy', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/components/navbar/')
  const drawer = page.locator('#docs-navbar'), trigger = page.getByRole('button', { name: 'Open navigation', exact: true })
  await drawer.evaluate(element => element.addEventListener('shown.trm.drawer', () => element.setAttribute('data-test-shown', 'true'), { once: true }))
  await trigger.click()
  await expect(drawer).toHaveAttribute('data-test-shown', 'true')
  await expect(page.locator('#docs-navbar:modal')).toHaveCount(1)
  await page.keyboard.press('Escape')
  await expect(drawer).not.toHaveAttribute('open')
  await expect(trigger).toBeFocused()
  await page.setViewportSize({ width: 1600, height: 1000 })
  const navbar = page.locator('nav.navbar').filter({has: drawer})
  await navbar.evaluate(element => { element.style.width = '1200px'; element.style.maxWidth = 'none' })
  await expect(drawer).toHaveCSS('position', 'static')
  await expect(drawer).toBeVisible()
  await expect(trigger).toBeHidden()
  await navbar.evaluate(element => { element.style.removeProperty('width'); element.style.removeProperty('max-width') })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(drawer).toBeHidden()
  await expect(page.locator('html')).not.toHaveClass(/dialog-open/)
})

test('Toggler changes configured classes/attributes, not Escape or hidden state', async ({ page }) => {
  await page.goto('/components/toggler/')
  const target = page.locator('#toggler-panel'), trigger = page.locator('[data-trm-target="#toggler-panel"]')
  await trigger.press('Enter')
  await expect(target).toHaveClass(/bg-2/)
  await trigger.press('Escape')
  await expect(target).toHaveClass(/bg-2/)
  await expect(trigger).toBeFocused()
  await trigger.press('Space')
  await expect(target).not.toHaveClass(/bg-2/)
  await page.locator('[data-trm-target="#toggler-custom"]').click()
  await expect(page.locator('#toggler-custom')).toHaveCSS('font-weight', '700')
  await page.locator('[data-trm-target="#toggler-custom"]').click()
  await expect(page.locator('#toggler-custom')).not.toHaveAttribute('style')
  await expect(page.locator('[data-trm-target="#toggler-disabled"]')).toBeDisabled()
  await expect(page.locator('#toggler-disabled')).not.toHaveClass(/bg-2/)
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()).violations).toEqual([])
})

