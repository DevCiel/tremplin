test('SVG-masked close buttons have visible geometry, native states and working dismissal', async ({ page }) => {
  await page.goto('/components/close-button/')
  const close = page.locator('.docs-example').first().getByRole('button', { name: 'Close example' })
  await expect(close).toHaveText('')
  await expect(close).toHaveCSS('opacity', '0.5')
  const visual = await close.evaluate(element => ({ mask: getComputedStyle(element).maskImage, color: getComputedStyle(element).backgroundColor, width: element.getBoundingClientRect().width, height: element.getBoundingClientRect().height }))
  expect(visual.mask).toContain('data:image/svg+xml')
  expect(visual.color).not.toBe('rgba(0, 0, 0, 0)')
  expect(visual.width).toBeGreaterThan(0)
  expect(visual.height).toBeGreaterThan(0)
  await expect(page.getByRole('button', { name: 'Unavailable close action' })).toBeDisabled()
  await page.getByRole('button', { name: 'Dismiss example message' }).click()
  await expect(page.locator('#reference-close-alert')).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('floating labels precede their controls and float on focus/value/native select', async ({ page }) => {
  await page.goto('/forms/floating-labels/')
  const input = page.getByLabel('Email address', { exact: true })
  const label = page.locator('label[for="forms-floating-email"]')
  expect(await input.evaluate(element => element.previousElementSibling?.tagName)).toBe('LABEL')
  await input.focus()
  await expect(label).not.toHaveCSS('transform', 'none')
  await input.fill('demo@example.com')
  await page.locator('h1').click()
  await expect(label).not.toHaveCSS('transform', 'none')
  const select = page.getByLabel('Role', { exact: true })
  await expect(select).toHaveClass('form-control')
  await expect(page.locator('label[for="forms-floating-role"]')).not.toHaveCSS('transform', 'none')
})

test('grouped controls and adorned focus work at narrow widths in both directions', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/forms/input-group/')
  for (const direction of ['ltr', 'rtl']) {
    await page.locator('html').evaluate((element, value) => element.setAttribute('dir', value), direction)
    const group = page.locator('[data-forms-demo="multiple"]')
    expect(await group.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
    await expect(group.getByLabel('First name')).toBeVisible()
    await expect(group.getByLabel('Last name')).toBeVisible()
  }
  await page.goto('/forms/form-adorn/')
  const website = page.getByLabel('Website', {exact: true})
  await website.focus()
  await expect(website).toBeFocused()
  await expect(page.locator('label.form-control.form-adorn[for="forms-adorn-site"]')).toHaveCSS('outline-style', 'solid')
})

test('validation explicitly styles errors, restores focus and recovers without submission', async ({ page }) => {
  await page.goto('/forms/validation/')
  const submissions: string[] = []
  page.on('request', request => { if (request.isNavigationRequest() || request.method() === 'POST') submissions.push(request.url()) })
  const form = page.locator('#forms-validation-demo')
  const input = form.getByRole('textbox')
  await form.getByRole('button', { name: 'Check details' }).click()
  await expect(form.locator('[data-error-summary]')).toBeFocused()
  await expect(form.locator('.invalid-feedback')).toBeVisible()
  await expect(input).toHaveClass(/is-invalid/)
  await expect(input).toHaveAttribute('aria-invalid', 'true')
  await form.getByRole('link', { name: 'Enter a valid email address' }).click()
  await expect(input).toBeFocused()
  await input.fill('demo@example.com')
  await form.getByRole('button', { name: 'Check details' }).click()
  await expect(form.locator('[data-error-summary]')).toBeHidden()
  await expect(form.locator('.invalid-feedback')).toBeHidden()
  await expect(input).toHaveAttribute('aria-invalid', 'false')
  await expect(input).toHaveClass(/is-valid/)
  await expect(form.getByRole('status')).toHaveText('Valid. This demo does not send data.')
  expect(submissions).toEqual([])
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()).violations).toEqual([])
})

test('native success feedback is explicitly scoped and follows user interaction', async ({ page }) => {
  await openScopedValidation(page)
  const required = page.locator('#required-field')
  await expect(page.locator('#required-feedback')).toBeHidden()
  await required.fill('Example')
  await required.press('Tab')
  await expect(page.locator('#required-feedback')).toBeVisible()
  await page.locator('#optional-field').fill('Optional value')
  await page.locator('#optional-field').press('Tab')
  await expect(page.locator('#optional-feedback')).toBeHidden()
  await required.clear()
  await required.press('Tab')
  await expect(page.locator('#required-feedback')).toBeHidden()
})
